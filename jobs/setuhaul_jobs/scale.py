"""Scale data: several generated facilities shaped like Jaipur, each with generated truck requests.

The plan's scale test is 240 shipments over 32 docks at 6 facilities. This adds facilities FAC-SCL-01, ... with the
docks spread as evenly as possible (each facility keeps at least one reefer and one heavy dock), Jaipur's opening
hours, rules and slot pattern (hourly slots 08:00-22:00, 90-minute slots on heavy docks), and the shipments spread
evenly, generated by the load-test generator. Use it on a database of its own, never the demo:

    python -m setuhaul_jobs.scale --database-url postgresql://...  [--facilities 6 --docks 32 --shipments 240]
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import sys

import psycopg

from setuhaul_jobs import scenario

TEMPLATE = "FAC-JAI-01"
ZONE = scenario.ZONE


def spread(total: int, parts: int) -> list[int]:
    """`total` split into `parts` near-equal whole numbers, larger first."""
    base, extra = divmod(total, parts)
    return [base + (1 if i < extra else 0) for i in range(parts)]


def dock_layout(count: int) -> list[tuple[str, str, int, int]]:
    """(code, type, max weight kg, refrigerated) for `count` docks: standard docks, then one reefer and one heavy."""
    if count < 3:
        raise ValueError("each facility needs at least 3 docks (standard, reefer, heavy)")
    docks = [(f"D{i + 1}", "STANDARD", 20000 if i % 2 == 0 else 25000, 0) for i in range(count - 2)]
    docks.append((f"D{count - 1}", "REEFER", 22000, 1))
    docks.append((f"D{count}", "HEAVY", 35000, 0))
    return docks


def slot_times(day: dt.date, dock_type: str) -> list[tuple[dt.datetime, dt.datetime]]:
    """Jaipur's pattern: hourly 08:00-22:00; heavy docks 90 minutes, last start by 20:00."""
    length = dt.timedelta(minutes=90 if dock_type == "HEAVY" else 60)
    start = dt.datetime.combine(day, dt.time(8, 0), ZONE)
    close = dt.datetime.combine(day, dt.time(22, 0), ZONE)
    out = []
    while start + length <= close:
        out.append((start, start + length))
        start += length
    return out


def build(conn: psycopg.Connection, *, facilities: int = 6, docks: int = 32, shipments: int = 240,
          seed: int = 7) -> list[str]:
    """Adds the facilities, docks, slots, rules and trucks in one transaction. Returns the facility ids."""
    if facilities < 1 or docks < 3 * facilities or shipments < 0:
        raise ValueError("need at least one facility and three docks per facility")
    with conn.transaction():
        (exists,) = conn.execute("SELECT count(*) FROM facilities WHERE facility_id LIKE 'FAC-SCL-%%'").fetchone()
        if exists:
            raise ValueError("scale facilities already exist; use a fresh database")
        (day,) = conn.execute(
            "SELECT min(slot_start_ts AT TIME ZONE 'Asia/Kolkata')::date FROM appointment_slots WHERE facility_id = %s",
            (TEMPLATE,)).fetchone()
        (created,) = conn.execute("SELECT min(created_at) FROM appointment_slots WHERE facility_id = %s",
                                  (TEMPLATE,)).fetchone()
        ids = []
        for n, (dock_count, trucks) in enumerate(zip(spread(docks, facilities), spread(shipments, facilities)), 1):
            fid = f"FAC-SCL-{n:02d}"
            ids.append(fid)
            conn.execute(
                """INSERT INTO facilities (facility_id, facility_name, city, state, timezone, open_time, close_time,
                       checkin_grace_min, default_unload_min, active_flag)
                   SELECT %s, %s, city, state, timezone, open_time, close_time, checkin_grace_min,
                          default_unload_min, active_flag FROM facilities WHERE facility_id = %s""",
                (fid, f"Scale test facility {n}", TEMPLATE))
            conn.execute(
                """INSERT INTO facility_rules (rule_id, facility_id, rule_type, rule_value, description, effective_from,
                       effective_to, active_flag)
                   SELECT %s || '-' || rule_id, %s, rule_type, rule_value, description, effective_from, effective_to,
                          active_flag FROM facility_rules WHERE facility_id = %s""",
                (fid, fid, TEMPLATE))
            slot_no = 0
            for code, dtype, max_kg, refr in dock_layout(dock_count):
                dock_id = f"DOCK-SCL{n:02d}-{code}"
                conn.execute(
                    """INSERT INTO docks (dock_id, facility_id, dock_code, dock_type, supports_refrigerated,
                           max_vehicle_weight_kg, dock_status) VALUES (%s, %s, %s, %s, %s, %s, 'ACTIVE')""",
                    (dock_id, fid, code, dtype, refr, max_kg))
                rows = []
                for start, end in slot_times(day, dtype):
                    slot_no += 1
                    rows.append((f"SLOT-SCL{n:02d}-{slot_no:03d}", fid, dock_id, start, end, created))
                conn.cursor().executemany(
                    """INSERT INTO appointment_slots (slot_id, facility_id, dock_id, slot_start_ts, slot_end_ts,
                           slot_status, created_at) VALUES (%s, %s, %s, %s, %s, 'OPEN', %s)""", rows)
            # All trucks known at the start (no trickle), so one run per facility sees the whole load.
            scenario.generate(conn, trucks=trucks, trickle=0, seed=seed * 1000 + n, facility=fid,
                              coordinator_cases=min(4, trucks))
    return ids


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--database-url", default=os.environ.get("DATABASE_URL"))
    parser.add_argument("--facilities", type=int, default=6)
    parser.add_argument("--docks", type=int, default=32)
    parser.add_argument("--shipments", type=int, default=240)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args(argv)
    if not args.database_url:
        parser.error("--database-url or DATABASE_URL is required")
    with psycopg.connect(args.database_url) as conn:
        ids = build(conn, facilities=args.facilities, docks=args.docks, shipments=args.shipments, seed=args.seed)
    print(f"{len(ids)} facilities ({', '.join(ids)}), {args.docks} docks, {args.shipments} truck requests")
    return 0


if __name__ == "__main__":
    sys.exit(main())

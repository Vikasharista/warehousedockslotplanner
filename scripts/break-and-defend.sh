#!/usr/bin/env bash
# Phase 6 evidence: the baseline comparison and the scale and stress tests, from scratch.
# Builds four throwaway databases next to yours (setuhaul_p6_snapshot, _load, _scale, _stress), solves them and
# writes the tables to docs/results/phase6/. Never touches the demo database.
#
#   PG_URL=postgresql://postgres:postgres@localhost:55432 scripts/break-and-defend.sh
#
# Needs: Postgres reachable at PG_URL, Python with jobs/requirements.txt (PYTHON, default .venv/bin/python),
# Java 17+ and Maven. Takes about 6 minutes (the solver runs at its production time limit).
# The end-to-end race harness needs the running stack instead: see jobs/README.md.
set -euo pipefail
cd "$(dirname "$0")/.."
PG_URL=${PG_URL:-postgresql://postgres:postgres@localhost:55432}
PYTHON=${PYTHON:-$PWD/.venv/bin/python}
OUT=docs/results/phase6
AS_OF=2026-08-04T09:55:00+05:30
mkdir -p "$OUT"

jdbc() {  # postgresql://user:pass@host:port/db -> jdbc:postgresql://host:port/db?user=..&password=..
  "$PYTHON" -c 'import sys, urllib.parse as u; p = u.urlparse(sys.argv[1]); user = p.username or "postgres"
pw = "&password=" + p.password if p.password else ""
print("jdbc:postgresql://%s:%s%s?user=%s%s" % (p.hostname, p.port or 5432, p.path, user, pw))' "$1"
}

fresh() {  # fresh <db>: an empty database, seeded from the snapshot with the clock at 09:55
  psql "$PG_URL/postgres" -qc "DROP DATABASE IF EXISTS $1" -c "CREATE DATABASE $1" >/dev/null
  (cd jobs && "$PYTHON" -m setuhaul_jobs.seed --database-url "$PG_URL/$1" --init >/dev/null)
}

echo "== building the solver"
mvn -q -B -f solver/pom.xml -pl core -DskipTests package
JAR=solver/core/target/dock-solver.jar
java_cli() { java -cp "$JAR" "com.setuhaul.solver.cli.$1" "${@:2}" 2>/dev/null; }

echo "== data"
fresh setuhaul_p6_snapshot
fresh setuhaul_p6_load
(cd jobs && "$PYTHON" -m setuhaul_jobs.scenario --database-url "$PG_URL/setuhaul_p6_load" --trucks 70 --trickle 20 --seed 1 >/dev/null)
fresh setuhaul_p6_scale
(cd jobs && "$PYTHON" -m setuhaul_jobs.scale --database-url "$PG_URL/setuhaul_p6_scale")
fresh setuhaul_p6_stress
(cd jobs && "$PYTHON" -m setuhaul_jobs.scale --database-url "$PG_URL/setuhaul_p6_stress" --docks 120 --shipments 1000)

echo "== baseline comparison"
{
  echo "# Baseline comparison"
  echo
  echo "Solver (production settings: warm start from priority-first, 10 s limit, 2 s unimproved), the same search"
  echo "from an empty plan (cold start, as before phase 6), first come first served, and priority first."
  echo "Generated by scripts/break-and-defend.sh."
  echo
  echo "## Supplied snapshot, 09:55"; echo
  java_cli Compare --jdbc-url "$(jdbc "$PG_URL/setuhaul_p6_snapshot")" --as-of "$AS_OF" --json "$OUT/compare-snapshot.json"
  for t in 09:55 12:00 15:00; do
    echo; echo "## 70-truck load-test day, $t"; echo
    java_cli Compare --jdbc-url "$(jdbc "$PG_URL/setuhaul_p6_load")" --as-of "2026-08-04T$t:00+05:30" \
      --json "$OUT/compare-load-${t/:/}.json"
  done
  echo; echo "## Scale set (6 facilities, 32 docks, 240 requests), 09:55"; echo
  java_cli Compare --jdbc-url "$(jdbc "$PG_URL/setuhaul_p6_scale")" --as-of "$AS_OF" --facility 'FAC-SCL-*' \
    --json "$OUT/compare-scale.json"
} > "$OUT/baseline.md"

echo "== scale and stress"
{
  echo "# Scale and stress"
  echo
  echo "Each facility planned on its own, as in production; pass = feasible plan within 60 s."
  echo "Generated by scripts/break-and-defend.sh."
  echo
  echo "## Scale test: 6 facilities, 32 docks, 240 requests (pass/fail)"; echo
  java_cli Scale --jdbc-url "$(jdbc "$PG_URL/setuhaul_p6_scale")" --as-of "$AS_OF" --json "$OUT/scale.json"
  echo; echo "## Stress run: 6 facilities, 120 docks, 1,000 requests (report only)"; echo
  java_cli Scale --jdbc-url "$(jdbc "$PG_URL/setuhaul_p6_stress")" --as-of "$AS_OF" --json "$OUT/stress.json" || true
} > "$OUT/scale.md"

echo "== written to $OUT"
ls "$OUT"

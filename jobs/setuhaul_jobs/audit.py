"""Run the data-audit queries in db/audit/ against Postgres and write docs/data-audit.md.

    python -m setuhaul_jobs.audit --database-url postgresql://... [--out docs/data-audit.md]

Each query file starts with ``-- id:``, ``-- title:`` and ``-- impact:`` header lines. The report shows
the finding, what the solver does about it, the query, and the rows it returned, so every finding
carries the query that proves it.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import psycopg

from .paths import AUDIT_DIR, AUDIT_REPORT, REPO_ROOT, SNAPSHOT_DB
from .seed import SNAPSHOT_TIMEZONE

HEADER = re.compile(r"^--\s*(id|title|impact):\s*(.+?)\s*$")


@dataclass(frozen=True)
class AuditQuery:
    path: Path
    id: str
    title: str
    impact: str
    sql: str


@dataclass(frozen=True)
class AuditResult:
    query: AuditQuery
    columns: list[str]
    rows: list[tuple]


def load_queries(directory: Path = AUDIT_DIR) -> list[AuditQuery]:
    queries = []
    for path in sorted(directory.glob("*.sql")):
        text = path.read_text()
        meta: dict[str, str] = {}
        for line in text.splitlines():
            m = HEADER.match(line)
            if m:
                meta[m.group(1)] = m.group(2)
        missing = {"id", "title", "impact"} - meta.keys()
        if missing:
            raise ValueError(f"{path.name}: missing header lines {sorted(missing)}")
        queries.append(AuditQuery(path, meta["id"], meta["title"], meta["impact"], text))
    ids = [q.id for q in queries]
    if len(ids) != len(set(ids)):
        raise ValueError(f"duplicate audit ids: {ids}")
    return queries


def run_queries(conn: psycopg.Connection, queries: list[AuditQuery]) -> list[AuditResult]:
    results = []
    with conn.transaction():
        conn.execute(f"SET LOCAL TIME ZONE '{SNAPSHOT_TIMEZONE}'")
        conn.execute("SET TRANSACTION READ ONLY")
        for q in queries:
            cur = conn.execute(q.sql)
            columns = [d.name for d in cur.description]
            results.append(AuditResult(q, columns, cur.fetchall()))
    return results


def fmt(value) -> str:
    if value is None:
        return ""
    if isinstance(value, dt.datetime):
        return value.strftime("%Y-%m-%d %H:%M")
    if isinstance(value, dt.time):
        return value.strftime("%H:%M")
    return str(value).replace("|", "\\|")


def render(results: list[AuditResult], snapshot: Path = SNAPSHOT_DB) -> str:
    digest = hashlib.sha256(snapshot.read_bytes()).hexdigest()[:12]
    lines = [
        "# Data audit: SetuHaul snapshot of 4 August 2026",
        "",
        "Generated by `python -m setuhaul_jobs.audit` from the queries in `db/audit/`, run against Postgres",
        f"seeded from `{snapshot.relative_to(REPO_ROOT)}` (sha256 `{digest}…`). Times are Asia/Kolkata.",
        "Do not edit by hand: change a query and re-run the job.",
        "",
        "| # | Finding | Rows |",
        "| --- | --- | --- |",
    ]
    for r in results:
        anchor = r.query.id.lower()
        lines.append(f"| [{r.query.id}](#{anchor}) | {r.query.title} | {len(r.rows)} |")
    for r in results:
        q = r.query
        body = "\n".join(l for l in q.sql.splitlines() if not HEADER.match(l)).strip()
        lines += [
            "",
            f'<a id="{q.id.lower()}"></a>',
            f"## {q.id}. {q.title}",
            "",
            f"**What the solver does:** {q.impact}",
            "",
            f"Query: [`{q.path.relative_to(REPO_ROOT)}`]({Path('..') / q.path.relative_to(REPO_ROOT)})",
            "",
            "```sql",
            body,
            "```",
            "",
        ]
        if r.rows:
            lines.append("| " + " | ".join(r.columns) + " |")
            lines.append("| " + " | ".join("---" for _ in r.columns) + " |")
            for row in r.rows:
                lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
        else:
            lines.append("No rows.")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--database-url", default=os.environ.get("DATABASE_URL"))
    parser.add_argument("--out", type=Path, default=AUDIT_REPORT)
    args = parser.parse_args(argv)
    if not args.database_url:
        parser.error("pass --database-url or set DATABASE_URL")
    try:
        with psycopg.connect(args.database_url) as conn:
            results = run_queries(conn, load_queries())
    except psycopg.Error as exc:
        print(f"audit failed: {exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(results))
    for r in results:
        print(f"{r.query.id:<4} {len(r.rows):>3} rows  {r.query.title}")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
